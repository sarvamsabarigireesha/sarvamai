export function inr(n) {
  return "₹" + Number(n).toLocaleString("en-IN");
}

export function compact(n) {
  if (n >= 1000000) return (n / 1000000).toFixed(2) + "M";
  if (n >= 1000) return (n / 1000).toFixed(n >= 10000 ? 0 : 1) + "K";
  return String(n);
}
